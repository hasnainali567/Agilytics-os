import { useState } from "react";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { Link } from "@tanstack/react-router";
import { TopBar } from "../components/layout";
import { Card, CardHeader, Field, Input, StatusPill } from "../components/ui";
import { createProject, fetchProjects, fetchTickets } from "../lib/api";

/** Projects — Kanban main design: white 18px cards on the #E9EEF5 page,
 *  create form on the shared Input primitives with a vivid purple
 *  #6C5CE7 submit button, and a 13px table (muted uppercase headers,
 *  hairline dividers, 11–12px status pills) for the list.
 *  List from GET /projects, create via POST /projects. The project key
 *  is generated by the API (first letters of the name). Ticket counts
 *  come from GET /tickets, grouped per project. */
export function ProjectsPage() {
  const queryClient = useQueryClient();
  const [name, setName] = useState("");
  const [description, setDescription] = useState("");
  const [formError, setFormError] = useState<string | null>(null);

  const projectsQuery = useQuery({
    queryKey: ["projects"],
    queryFn: fetchProjects,
    retry: false,
  });
  const ticketsQuery = useQuery({
    queryKey: ["tickets"],
    queryFn: () => fetchTickets(),
    retry: false,
  });

  const create = useMutation({
    mutationFn: () =>
      createProject({ name: name.trim(), description: description.trim() || undefined }),
    onSuccess: () => {
      setName("");
      setDescription("");
      setFormError(null);
      queryClient.invalidateQueries({ queryKey: ["projects"] });
      queryClient.invalidateQueries({ queryKey: ["boards"] });
    },
    onError: (err) => setFormError(err.message),
  });

  const projects = projectsQuery.data ?? [];
  const ticketCounts = new Map<string, number>();
  for (const t of ticketsQuery.data ?? []) {
    ticketCounts.set(t.projectId, (ticketCounts.get(t.projectId) ?? 0) + 1);
  }

  return (
    <div className="flex min-h-full flex-col bg-[#E9EEF5]">
      <TopBar title="Projects" />
      <main className="space-y-5 px-6 py-6 lg:px-8">
        <Card>
          <CardHeader
            title="New project"
            subtitle="A default board (Backlog / To Do / In Progress / Review / Done) is created with it."
          />
          <form
            className="flex flex-wrap items-end gap-3 px-5 py-4"
            onSubmit={(e) => {
              e.preventDefault();
              setFormError(null);
              create.mutate();
            }}
          >
            <Field label="Name" className="w-64">
              <Input
                value={name}
                onChange={(e) => setName(e.target.value)}
                placeholder="e.g. Mobile App"
                className="w-full"
              />
            </Field>
            <Field label="Description" className="min-w-64 flex-1">
              <Input
                value={description}
                onChange={(e) => setDescription(e.target.value)}
                placeholder="What this project is for"
                className="w-full"
              />
            </Field>
            <button
              type="submit"
              disabled={create.isPending}
              className="rounded-[10px] bg-[#6C5CE7] px-4 py-2 text-sm font-medium text-white transition-colors hover:bg-[#5B4BD6] disabled:opacity-50"
            >
              {create.isPending ? "Creating…" : "Create project"}
            </button>
            {formError ? <p className="w-full text-sm text-risk">{formError}</p> : null}
          </form>
        </Card>

        <Card className="overflow-hidden">
          <CardHeader title="All projects" subtitle={`${projects.length} project${projects.length === 1 ? "" : "s"}`} />
          {projectsQuery.isPending ? (
            <p className="p-5 text-sm text-muted">Loading projects…</p>
          ) : projectsQuery.isError || !projectsQuery.data ? (
            <p className="p-5 text-sm text-muted">
              The projects API isn't reachable yet — start the API and sign in.
            </p>
          ) : projects.length === 0 ? (
            <p className="p-5 text-sm text-muted">
              No projects yet — create your first one above.
            </p>
          ) : (
            <table className="w-full text-left text-[13px]">
              <thead>
                <tr className="border-b border-line text-xs uppercase tracking-wide text-muted">
                  <th className="px-5 py-3 font-medium">Project</th>
                  <th className="px-5 py-3 font-medium">Key</th>
                  <th className="px-5 py-3 font-medium tabular-nums">Tickets</th>
                  <th className="px-5 py-3 font-medium">Status</th>
                  <th className="px-5 py-3 font-medium">Created</th>
                  <th className="px-5 py-3 font-medium">
                    <span className="sr-only">Open</span>
                  </th>
                </tr>
              </thead>
              <tbody>
                {projects.map((p) => (
                  <tr key={p.id} className="border-b border-line last:border-0 hover:bg-[#F7F8FA]">
                    <td className="px-5 py-3">
                      <p className="font-medium text-ink">{p.name}</p>
                      {p.description ? (
                        <p className="mt-0.5 max-w-md truncate text-xs text-muted">{p.description}</p>
                      ) : null}
                    </td>
                    <td className="px-5 py-3">
                      <span className="rounded-full bg-[#EFEAFE] px-2.5 py-0.5 text-xs font-semibold text-[#6C5CE7]">
                        {p.key}
                      </span>
                    </td>
                    <td className="px-5 py-3 tabular-nums text-ink">
                      {ticketCounts.get(p.id) ?? 0}
                    </td>
                    <td className="px-5 py-3">
                      <StatusPill status={p.status} />
                    </td>
                    <td className="px-5 py-3 text-muted">
                      {new Date(p.createdAt).toLocaleDateString()}
                    </td>
                    <td className="px-5 py-3 text-right">
                      <Link
                        to="/boards"
                        className="inline-block rounded-[10px] bg-[#6C5CE7] px-4 py-1.5 text-xs font-medium text-white transition-colors hover:bg-[#5B4BD6]"
                      >
                        Open board
                      </Link>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          )}
        </Card>
      </main>
    </div>
  );
}
